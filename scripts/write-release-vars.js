#!/usr/bin/env node
/*
  Writes src/scss/brand/_release.scss before each build, so the CSS can point at
  its own release folder with full addresses (fonts). Full addresses are needed
  because WordPress copies editor styles into the editor page, where a relative
  "../fonts/" address would point at wp-admin instead of the media server.
*/
const fs = require("fs");
const path = require("path");

const version = require(path.join(process.cwd(), "package.json")).version;
const base = (process.env.MEDIA_PUBLIC_URL || "https://media.cruiseandthemeparkguide.com").replace(/\/$/, "");
const out = path.join(process.cwd(), "src", "scss", "brand", "_release.scss");
const body =
  "// Generated by scripts/write-release-vars.js on every build. Do not edit.\n" +
  `$ctpg-release-version: "${version}";\n` +
  `$ctpg-asset-base: "${base}/v/${version}";\n`;
fs.writeFileSync(out, body);
console.log(`release vars: ${base}/v/${version}`);
